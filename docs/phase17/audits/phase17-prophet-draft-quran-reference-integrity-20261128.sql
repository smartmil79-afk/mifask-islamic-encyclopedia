checked AS (
  SELECT
    r.surah_number,
    r.ayah_number,
    v.arabic,
    v.translations->'en'->>'text' AS english_text,
    v.translations->'en'->>'edition' AS edition
  FROM draft_refs r
  LEFT JOIN public.ie_quran_verses v
    ON v.surah_number = r.surah_number
   AND v.ayah_number = r.ayah_number
)
SELECT
  count(*) AS unique_draft_coordinates,
  count(*) FILTER (WHERE arabic IS NOT NULL) AS resolved_local_verses,
  count(*) FILTER (WHERE arabic IS NULL) AS unresolved_coordinates,
  count(*) FILTER (
    WHERE arabic IS NOT NULL AND nullif(btrim(arabic), '') IS NULL
  ) AS arabic_text_gaps,
  count(*) FILTER (
    WHERE arabic IS NOT NULL AND nullif(btrim(english_text), '') IS NULL
  ) AS english_text_gaps,
  count(*) FILTER (
    WHERE arabic IS NOT NULL AND nullif(btrim(edition), '') IS NULL
  ) AS edition_gaps,
  coalesce(
    jsonb_agg(
      jsonb_build_object('surah', surah_number, 'ayah', ayah_number)
      ORDER BY surah_number, ayah_number
    ) FILTER (WHERE arabic IS NULL),
    '[]'::jsonb
  ) AS unresolved_coordinates_list
FROM checked;
